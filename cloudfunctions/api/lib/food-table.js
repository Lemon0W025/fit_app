const VEG = '青菜|小青菜|小白菜|上海青|油菜|菜心|生菜|菠菜|油麦菜|空心菜|西兰花|西蓝花|包菜|卷心菜|圆白菜|白菜|大白菜|娃娃菜|芹菜|西芹|豆芽|绿豆芽|黄豆芽|芥蓝|芥兰|莴笋|莴苣|西葫芦|黄瓜|冬瓜|丝瓜|苦瓜|茼蒿|韭菜|苋菜|豆苗|花菜|菜花|青椒|蘑菇|香菇|木耳|胡萝卜|萝卜|白萝卜|芦笋|秋葵|茭白|笋|竹笋|海带|时蔬|时令蔬菜|蔬菜|素菜'
const VEG_WAYS = [
  // 炒的（没写做法的也当炒的）
  { ways: '清炒|蒜蓉|蒜炒|炒|素炒|蚝油|醋溜|手撕|炝炒|炝|上汤|', row: [55, 2, 3.5, 3.5, 'D'] },
  // 水里过的
  { ways: '白灼|水煮|烫|焯|清煮|蒸|清蒸|煮', row: [30, 2, 3.5, 1, 'D'] },
  { ways: '凉拌|拍|蒜泥|糖醋|酸辣', row: [45, 1.2, 3.5, 3, 'D'] },
]

function entry(names, [kcal, protein, carbs, fat, tol]) {
  return { name: names[0], names, kcal, protein, carbs, fat, tol: TOL[tol] }
}

const ENTRIES = ROWS.map((r) => entry(r[0].split('|'), r.slice(1)))
const BY_NAME = new Map()
ENTRIES.forEach((e) => e.names.forEach((n) => BY_NAME.set(n, e)))
const ALIASES = Array.from(BY_NAME.keys()).sort((a, b) => b.length - a.length)

const VEG_RULES = VEG_WAYS.map((w) => ({
  re: new RegExp(`^(?:${w.ways})(?:${VEG})$`),
  entry: entry(['青菜'], w.row),
}))

// 「米饭（一碗）」「 家常 红烧肉 」→「米饭」「红烧肉」
function clean(name) {
  const n = String(name || '')
    .replace(/[（(【\[].*?[)）】\]]/g, '')
    .replace(/[\s·、，,。.!！~～]/g, '')
  const bare = n.replace(FILLER, '')
  return bare || n
}

function lookup(name) {
  const n = clean(name)
  if (!n) return null
  if (BY_NAME.has(n)) return BY_NAME.get(n)
  const veg = VEG_RULES.find((r) => r.re.test(n))
  if (veg) return veg.entry
  const alias = ALIASES.find(
    (a) => a.length >= TAIL_MIN && a.length / n.length >= COVER && n.endsWith(a) && BY_NAME.get(a).kcal >= TAIL_KCAL_MIN,
  )
  return alias ? BY_NAME.get(alias) : null
}

function anchor(dish) {
  if (!dish || !(dish.grams > 0) || !(dish.kcal >= 0)) return dish
  const ref = lookup(dish.name)
  if (!ref) return dish
  const per100 = (dish.kcal / dish.grams) * 100
  const lo = ref.kcal * (1 - ref.tol)
  const hi = Math.max(ref.kcal * (1 + ref.tol), ref.kcal + ZERO_ROOM)
  if (per100 >= lo && per100 <= hi) return dish
  const target = per100 < lo ? lo : hi
  const next = { ...dish, kcal: Math.round((dish.grams * target) / 100) }
  // 营养素：表里的配比，按拉到的那个热量缩放
  if (typeof dish.protein === 'number') {
    const k = ref.kcal > 0 ? target / ref.kcal : 0
    ;['protein', 'carbs', 'fat'].forEach((m) => {
      next[m] = round1((dish.grams * ref[m] * k) / 100)
    })
  }
  return next
}

// 提示词里的参考：最常吃的十几样
const REF_NAMES = ['米饭', '白粥', '馒头', '面条', '饺子', '鸡蛋', '牛奶', '豆腐', '番茄炒蛋', '青椒肉丝', '红烧肉', '清蒸鱼', '白灼虾', '苹果', '啤酒']

function promptRefs() {
  const veg = VEG_RULES[0].entry
  return REF_NAMES.map((n) => `${n} ${BY_NAME.get(n).kcal}`).concat(`炒青菜 ${veg.kcal}`).join('、')
}

