  30: '一个月了，这已经是习惯啦',
  60: '两个月天天打卡，小暖都佩服你',
  100: '一百天！你比小暖还坚持',
  150: '一百五十天，营地里的大家都看着呢',
  200: '两百天，好好吃饭已经刻进日子里了',
  300: '三百天，真的很了不起',
  365: '整整一年！每一顿都算数',
